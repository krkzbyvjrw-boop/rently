export const messages: Record<Locale, typeof en> = { en, lt, ru }

export function getMessage(locale: Locale, key: string): string {
  const parts = key.split('.')
  let cur: unknown = messages[locale]
  for (const part of parts) {
    if (cur && typeof cur === 'object' && part in cur) {
      cur = (cur as Record<string, unknown>)[part]
    } else {
      return key
    }
  }
  return typeof cur === 'string' ? cur : key
}

export function interpolate(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? ''))
}

export function isLocale(value: string | null): value is Locale {
  return value === 'en' || value === 'lt' || value === 'ru'
}

/** Translate bike category tag if we have a key; otherwise return as-is. */
export function bikeTypeLabel(locale: Locale, tag: string): string {
  const msg = getMessage(locale, `bikeType.${tag}`)
  return msg.startsWith('bikeType.') ? tag : msg
}
